// tests/integration/settings-carrier-retirement/security-delivery.test.ts — **THE SECURITY RECORD GETS THE DELIVERY IT NEVER
// HAD** (`D-106`; the rule `D-104` read as the architecture).
//
// AUTHORED AFTER the `D-30` sweep, so this file carries NO `strata:marked` marker and GATES (D-40, `AGENTS.md`).
//
// ═══ THE RULE, IN THE USER'S OWN WORDS ═══
// **"The renderer does not ask state, it listens. If it needs to ask, it does so within a listener."** `D-104` audited every
// renderer→crossing read at its own head, classified each exactly once, and named `SecurePanels.refresh()`'s read of
// `security.get()` as the ONE that remained: an ON-DEMAND ASK, made at request time from the boot, from EVERY authored click
// (`handleDomEvent`) and from the `dispatch()` seam. **The crossing's half already existed** — the instance's one
// subscription has always bound `['operator-settings']` and the `mem` `['operator-exclusion']`, and `onDelivery` has always
// acted on them — but **no delivery crossed to the renderer**: `grep "SECURITY_CHANGED|security:changed" src/ tests/`
// answered ZERO, where the other three families each had a channel. This battery is the measurement that the missing half is
// built and that the ask is gone.
//
// ═══ THIS FILE IS A SIBLING, AND WHY ═══
// `app-state-delivery.test.ts` (`D-104`) is the app-state rows' battery: its subject is `['operator-app-state']`, whose
// delivery body is the surface's SECOND. This one's subject is the record and the pair, whose delivery body is the FIRST —
// a different address, a different body, a different channel — so it is a sibling and not a row in that file. **IT IS ALSO
// WHY `strata/marks.json` IS REGENERATED BY `strata-marks.mjs index`: a test file is added.**
//
// ═══ WHAT IS DRIVEN, AND WHAT IS NOT ═══
// The subject is the composition `src/main/main.ts` builds, in the order it builds it — the surface over a real
// `provident-storeroom` instance on a scratch profile, `attach` of a sink, the composition's broadcast, the bridge member
// `src/main/preload.ts` exposes, and `src/renderer/security-client.ts` — so no row here is a stand-in for a mechanism the
// app does not have. **TWO THINGS ARE THE NODE SUITE'S AND ARE NAMED RATHER THAN HIDDEN**: the `BrowserWindow` fan-out is
// `main.ts`'s and is not constructible here (`main.ts` imports `electron` at module scope), so the broadcast is the
// composition's own callback and the bridge's `onChanged` is the one the preload registers on the same channel; and the
// renderer's `startSecurityShape` is not importable for the same reason, so the rows drive the client's two turns —
// `subscribe` then ONE `fill` — exactly as that function does, and the pane's adopt step is `SecurePanels.applySecurity`,
// which `SD-3` reads as code and `SD-2`'s equality holds to the same shape.
//
// **EVERY ROW CAN FAIL.** `SD-1`'s revert is the one this pass' instruction names: remove the surface's broadcast call and
// the delivery count returns to ZERO. `SD-3` is the structural half — an assertion over COMMENT-ELIDED code that the
// security read sits inside the listener and nowhere at request time — and its own revert is a read put back in `refresh()`.
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { afterEach, beforeEach, describe, expect, it } from 'vitest'

import { createSettingsSurface } from '../../../src/main/settings-surface/index.js'
import { createSecurityClient } from '../../../src/renderer/security-client.js'

const ROOT = fileURLToPath(new URL('../../../', import.meta.url))

/** The registry's row prefix, spelled here as `main.ts` spells it (a name is a member of a row, never a path segment). */
const PREFIX = 'file.modules.'
const SOURCE = 'export const greeting = () => "hello"'
const sha256 = (source: string): string => createHash('sha256').update(source, 'utf8').digest('hex')

/** One module row, in the shape `main.ts`'s `put` composes — the app-state family's own act, used by the CONTROL row. */
function moduleRow(name: string, version: string): { name: string; value: unknown } {
  return { name: `${PREFIX}${name}`, value: { name, version, source: SOURCE, hash: sha256(SOURCE), installedAt: '2026-11-03T00:00:00.000Z', disabled: false, quarantined: false } }
}

interface Composition {
  surface: ReturnType<typeof createSettingsSurface>
  client: ReturnType<typeof createSecurityClient>
  /** The composition's broadcast: how many times the surface called it, and how many handler invocations reached the realm. */
  readonly broadcasts: { count: number }
  readonly handlerCalls: () => number
  set(patch: { token?: string | null; groups?: string[]; disable?: string[]; maxJournalLength?: number | null }): void
  transition(state: 'mcp-enabled' | 'mcp-disabled'): void
  commitRows(rows: readonly { name: string; value: unknown }[]): void
  settle(): Promise<void>
}

/** **THE COMPOSITION `main.ts` BUILDS, IN ITS OWN ORDER** — surface, sink, broadcast, bridge, client, one boot fill. */
function compose(userDataDir: string): Composition {
  const handlers: Array<() => void> = []
  const broadcasts = { count: 0 }
  let calls = 0
  // THE BROADCAST IS THE COMPOSITION'S CALLBACK (`src/main/main.ts`'s `onSecurityChanged`), and the bridge's `onChanged` is
  // the preload's own registration on `IPC_SECURITY_CHANGED`: here the two are joined by a function call, which is the whole
  // of what the channel does between them.
  const surface = createSettingsSurface({
    userDataDir,
    onSecurityChanged: () => {
      broadcasts.count += 1
      for (const handler of handlers) handler()
    },
  })
  surface.attach({
    applyGatePatch: () => undefined,
    applyExclusion: () => undefined,
    gate: { exclusionState: () => 'mcp-enabled' },
  })
  const bridge = {
    // `IPC_SECURITY_GET`'s answer, member for member: the surface's own `read()`, which is what `main.ts`'s handler serves.
    get: async () => surface.read(),
    onChanged: (handler: () => void): (() => void) => {
      handlers.push(handler)
      return () => {
        const at = handlers.indexOf(handler)
        if (at >= 0) handlers.splice(at, 1)
      }
    },
  }
  const client = createSecurityClient({ bridge: bridge as never })
  // THE ROW COUNTS THE REALM'S HANDLER INVOCATIONS, never the broadcast: a delivery that crossed the channel but reached no
  // listener would leave this counter still and the row red.
  client.subscribe(() => {
    calls += 1
  })
  return {
    surface,
    client,
    broadcasts,
    handlerCalls: () => calls,
    set: (patch) => {
      const answer = surface.set(patch)
      if (answer.write.status !== 'committed') throw new Error(`the record write was REFUSED: ${JSON.stringify(answer.write)}`)
    },
    transition: (state) => {
      const answer = surface.transition(state)
      if (!answer.applied) throw new Error(`the exclusion transition was not applied: ${JSON.stringify(answer)}`)
    },
    commitRows: (rows) => {
      const answer = surface.commit(rows)
      if (answer.status !== 'committed') throw new Error(`the module-row commit was REFUSED: ${JSON.stringify(answer)}`)
    },
    // THE CLIENT'S READ IS ASYNCHRONOUS (a delivery is a RE-READ), so a row that asserts a refilled shape awaits one turn.
    settle: () => new Promise<void>((resolve) => setTimeout(resolve, 0)),
  }
}

let dir: string
beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'provident-security-delivery-'))
})
afterEach(() => {
  rmSync(dir, { recursive: true, force: true })
})

/** **COMMENTS ELIDED** — the absence and presence assertions below read CODE: a `//` line and every `/* … *\/` block are
 *  removed before a claim is made, so no row can pass on a comment that mentions a name (`D-103`'s `L-6` discipline). */
function elided(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => {
      const at = line.indexOf('//')
      return at >= 0 ? line.slice(0, at) : line
    })
    .join('\n')
}

const sourceOf = (path: string): string => readFileSync(join(ROOT, path), 'utf8')

describe('settings-carrier-retirement · THE SECURITY RECORD’S DELIVERY (D-106)', () => {
  it('SD-1 · A SECURITY-RECORD CHANGE COMMITTED MAIN-SIDE DELIVERS TO THE RENDERER WITHOUT THE RENDERER ASKING — measured by the realm’s own handler counter, ZERO before the change, and the count is right on REVERT', async () => {
    const composed = compose(dir)
    await composed.client.fill()
    expect(composed.handlerCalls(), 'the boot fill is a READ and never a delivery: the subscription’s handler has not run').toBe(0)
    expect(composed.broadcasts.count, 'and the composition has broadcast nothing yet: no security act has been committed').toBe(0)

    // ONE record write, the way the operator's pane commits it — `security.set` → the surface's `set` → ONE store commit.
    composed.set({ token: 'tok-1', groups: ['graph'] })
    expect(composed.broadcasts.count, 'the surface handed the change to the composition’s broadcast INSIDE the write — before the commit’s own answer').toBe(1)
    await composed.settle()
    expect(composed.handlerCalls(), 'and it crossed the channel to the realm’s registered handler with NOTHING asked for by the realm').toBe(1)

    // THE `mem` PAIR IS THE SAME SUBSCRIPTION'S SECOND ADDRESS, and its transition delivers too.
    composed.transition('mcp-disabled')
    await composed.settle()
    expect(composed.handlerCalls(), 'an exclusion transition is a second delivery of the SAME record — one read answers both, so one channel carries both').toBe(2)
    expect(composed.broadcasts.count, 'and a second broadcast').toBe(2)
    expect(composed.client.shape().exclusion, 'and the realm’s shape carries the state it was TOLD about').toBe('mcp-disabled')

    // A THIRD act delivers again — the addresses are bound to the one subscription, not to one lucky instant.
    composed.set({ token: 'tok-2' })
    await composed.settle()
    expect(composed.handlerCalls(), 'a third security-record change is a third delivery, and the count is EXACT: remove the surface’s broadcast call and this row reads 0, 0, 0 (the revert this pass drives)').toBe(3)
  })

  it('SD-2 · THE SHAPE CARRIES THE RECORD AFTER THE DELIVERY, AND ITS VALUE EQUALS WHAT A READ WOULD HAVE ANSWERED — so the shape is not a guess', async () => {
    const composed = compose(dir)
    expect(composed.client.shape().filled, 'nothing has answered yet, so the shape says so: no delivery, and the boot read has not run').toBe(false)
    expect(composed.client.shape().exclusion, 'and the additive pair member is the `null` of “no reading yet” (`D-vi`), never a fabricated word').toBe(null)

    composed.set({ token: 'tok-1', groups: ['graph', 'data'], maxJournalLength: 9 })
    await composed.settle()
    const shape = composed.client.shape()
    expect(shape.filled, 'the delivery refilled the shape').toBe(true)

    // THE EQUALITY IS AGAINST A READ TAKEN NOW, not against the values this file wrote: the bridge’s own `get` is the route
    // the app reads through, so the shape must answer exactly what asking would have answered.
    const readNow = await composed.client.fill()
    expect(readNow.status, 'the read taken now is the committed arm').toBe('committed')
    if (readNow.status !== 'committed') throw new Error('unreachable: asserted above')
    expect({ token: shape.token, enabled: shape.enabled, maxJournalLength: shape.maxJournalLength, exclusion: shape.exclusion, read: shape.read }).toEqual({
      token: readNow.token,
      enabled: readNow.enabled,
      maxJournalLength: readNow.maxJournalLength,
      exclusion: readNow.exclusion,
      read: readNow.read,
    })
    expect(shape.enabled, 'and the three grant names are the record’s own set, in the record’s own order').toEqual(['read', 'dispatch', 'graph', 'data'])
    expect(shape.maxJournalLength, 'and the operator’s cap is the durable member the crossing answered').toBe(9)

    // THE TIER-4 ARM MOVES WITH THE PAIR, and the shape follows it — the additive member is delivered, never derived.
    composed.transition('mcp-disabled')
    await composed.settle()
    expect(composed.client.shape().exclusion, 'a closed pair is a delivery like any other').toBe('mcp-disabled')
    expect(composed.client.shape().read, 'and the read arm carries the refusal the surface mints for the closed state').not.toBe(null)
  })

  it('SD-3 · NO PULL REMAINS FOR THE SECURITY RECORD EITHER — over COMMENT-ELIDED code: the read lives in ONE file, inside the listener’s own re-read, and the pane asks the record nothing', () => {
    const rendererFiles = ['src/renderer/renderer.ts', 'src/renderer/secure-panels.ts', 'src/renderer/security-client.ts', 'src/renderer/module-client.ts', 'src/renderer/tabs-client.ts', 'src/renderer/view-client.ts', 'src/renderer/runtime.ts', 'src/renderer/extensions.ts']
    const code = new Map(rendererFiles.map((path) => [path, elided(sourceOf(path))]))

    // (a) **THE PANE ASKS THE RECORD NOTHING — this is the assertion the pull's revert reds.** The read that stood in
    //     `refresh()` was `const security = … window.provident?.security; … this.cfg = await security.get()`; planting it
    //     back makes the first of these two readings non-zero and this row RED.
    const panels = code.get('src/renderer/secure-panels.ts') as string
    expect(/security\s*\??\.\s*get\s*\(/.test(panels), 'the pane performs NO security read: no `security.get(...)` stands in `secure-panels.ts` at all').toBe(false)
    expect(/securityBridge|const security\s*=\s*typeof window/.test(panels), 'and it acquires no bridge binding to read one through').toBe(false)
    expect(/applySecurity/.test(panels), 'what fills its `cfg` is a DELIVERY’s turn, by name').toBe(true)

    // (b) THE READ SITS INSIDE THE LISTENER. In `security-client.ts` the route is invoked ONCE, in `fill`; `fill` is invoked
    //     from the subscription’s body — the delivery’s duty — and once more by the export the consumer’s ONE stated boot
    //     fill calls. The pane’s `refresh()` is a PAINT, and the census says so member by member.
    const client = code.get('src/renderer/security-client.ts') as string
    expect((client.match(/getRoute as \(\) => Promise<unknown>\)\.call\(member\)/g) ?? []).length, 'the security read is ONE expression, inside `fill`').toBe(1)
    expect((client.match(/void fill\(\)\.then\(/g) ?? []).length, 'and `fill` is invoked from the subscription’s own body: a delivery is a re-read').toBe(1)
    const fillBodyAt = client.indexOf('async function fill(')
    const callAt = client.indexOf('.call(member)')
    expect(fillBodyAt, '`fill` is the function that holds the read').toBeGreaterThan(-1)
    expect(callAt, 'and the read stands INSIDE it, never beside it').toBeGreaterThan(fillBodyAt)

    // (c) **THE TWO REQUEST-TIME SITES ARE GONE BY NAME.** `refresh()` was called at the boot, from `handleDomEvent` after
    //     EVERY authored click, and from the `dispatch()` seam — and it was the READ those three sites performed. The method
    //     is a paint now: its body is the two statements below and nothing else, so no arm of it can ask.
    const refreshAt = panels.indexOf('refresh(): void {')
    expect(refreshAt, '`refresh()` is still the paint the three sites call, and it is declared synchronous: a paint awaits nothing').toBeGreaterThan(-1)
    const refreshBody = (panels.slice(refreshAt + 'refresh(): void {'.length).split('\n  }')[0] as string)
    expect(refreshBody.replace(/\s+/g, ''), 'and its whole body is the paint: `syncConfig()` then `render()` — the read is DELETED, not guarded').toBe('this.syncConfig()this.render()')

    // (d) THE WIRING’S TWO TURNS — one registration and one stated boot fill — and no third call site, scoped to the ONE
    //     function (`startSecurityShape`), because the wiring module holds three other clients whose own boot fills are not
    //     this subject.
    const wiring = code.get('src/renderer/renderer.ts') as string
    expect((wiring.match(/startSecurityShape\(panels\)/g) ?? []).length, 'the shape is started at ONE boot site').toBe(1)
    const at = wiring.indexOf('function startSecurityShape(')
    expect(at, 'the boot site is one function, named').toBeGreaterThan(-1)
    const shapeBody = wiring.slice(at, wiring.indexOf('\nfunction ', at + 1) === -1 ? undefined : wiring.indexOf('\nfunction ', at + 1))
    expect((shapeBody.match(/client\.subscribe\(/g) ?? []).length, 'that function takes ONE subscription').toBe(1)
    expect((shapeBody.match(/client\.fill\(\)/g) ?? []).length, 'and performs the ONE stated boot read, never a second').toBe(1)
    expect((shapeBody.match(/panels\?\.applySecurity\(/g) ?? []).length, 'and the ONLY two turns that reach the consumer are the delivery’s and the boot fill’s').toBe(2)

    // (e) **THE ONE READ THIS REALM MAKES OUTSIDE THE CLIENT IS NAMED AND IS NOT A COUNTERPART** (`D-104`’s audit class (i)):
    //     `main()`’s `bridge.security.get()` is the TIER-4 SNAPSHOT the app Runtime’s Supervisor is constructed from — a boot
    //     fill whose value a construction consumes and which paints nothing. Exactly one stands in the wiring, and it is that.
    expect((wiring.match(/security\s*\??\.\s*get\s*\(/g) ?? []).length, 'exactly ONE security read stands in the wiring module, and it is the tier-4 boot snapshot').toBe(1)
    expect(/maxJournalLength = cfg\.maxJournalLength/.test(wiring), 'and it is the snapshot: the value it takes is the Supervisor’s `maxJournalLength` and nothing else').toBe(true)
  })

  it('SD-4 · THE CONTROL: A DELIVERY FOR A FAMILY THE RENDERER DOES NOT LISTEN TO DOES NOTHING — an APP-STATE commit moves neither the security counter nor the shape', async () => {
    const composed = compose(dir)
    await composed.client.fill()
    composed.set({ token: 'tok-1' })
    await composed.settle()
    const afterRecord = composed.client.shape()
    const callsAfterRecord = composed.handlerCalls()
    expect(callsAfterRecord, 'the record’s delivery is the one this battery counts').toBe(1)

    // THE THIRD ADDRESS IS BOUND TO THE SAME SUBSCRIPTION AND ROUTED TO THE SURFACE’S **OTHER** BODY (`D-104`), so its
    // deliveries reach `onAppStateChanged` — which this composition did not supply — and never this channel.
    composed.commitRows([moduleRow('alpha', '1.0.0')])
    await composed.settle()

    expect(composed.broadcasts.count, 'the composition broadcast NOTHING for the app-state family: the record’s push is the other body’s alone').toBe(1)
    expect(composed.handlerCalls(), 'the security realm’s handler did not run').toBe(callsAfterRecord)
    expect(composed.client.shape(), 'and the shape is the shape the record’s delivery left, member for member').toEqual(afterRecord)
  })

  it('SD-5 · THE TWO MAIN-SIDE HALVES AND THE LOCKSTEP PAIR — the surface hands the record’s delivery to the composition, and BOTH lockstep declarations carry the one member', () => {
    // THE SURFACE: the broadcast is called INSIDE the delivery body, for the record and the pair, and never at a call site.
    const surface = elided(sourceOf('src/main/settings-surface/index.ts'))
    expect(/onSecurityChanged\?: \(\) => void/.test(surface), 'the surface declares the push as its own option, optional like the app-state one').toBe(true)
    const deliveryAt = surface.indexOf('const onDelivery = ')
    expect(deliveryAt, 'the record’s delivery body is declared once, by name').toBeGreaterThan(-1)
    const body = surface.slice(deliveryAt, surface.indexOf('\n  }', deliveryAt))
    expect(/options\.onSecurityChanged\?\.\(\)/.test(body), 'and the broadcast is called INSIDE it — never at a call site, a poll or a boot-order re-read').toBe(true)
    expect((surface.match(/options\.onSecurityChanged\?\.\(\)/g) ?? []).length, 'and exactly once: one delivery, one signal').toBe(1)
    // IT IS CALLED BEFORE THE SINK'S ARMS, so a surface with no attached gate still tells the realm.
    expect(body.indexOf('options.onSecurityChanged?.()') < body.indexOf('const held = sink'), 'the call precedes the sink’s arms, so a composition whose gate was never built still delivers').toBe(true)

    // THE COMPOSITION: the broadcast names the channel constant and no literal, and every window is told.
    const main = elided(sourceOf('src/main/main.ts'))
    expect(/webContents\.send\(IPC_SECURITY_CHANGED\)/.test(main), '`main.ts` broadcasts the channel constant — never a literal — to the window it holds').toBe(true)
    expect(/onSecurityChanged: \(\) =>/.test(main), 'and the surface’s option is what it points at').toBe(true)

    // THE CHANNEL: one constant, in the shared vocabulary, and it names NO address (`ISO-5`/`ISO-6`).
    const types = elided(sourceOf('src/shared/types.ts'))
    expect(/export const IPC_SECURITY_CHANGED = 'provident:security:changed'/.test(types), 'the channel constant is declared in `src/shared/types.ts` beside its security siblings').toBe(true)
    expect(/operator-settings|operator-exclusion/.test(types), 'and this file names no address: the push carries none').toBe(false)

    // THE LOCKSTEP PAIR — the same member, in both halves, and the preload registers the constant rather than a literal.
    const preload = elided(sourceOf('src/main/preload.ts'))
    const panelsHalf = elided(sourceOf('src/renderer/secure-panels.ts'))
    const memberOf = (source: string, label: string): string => {
      const marker = /(\n\s*)security[?]?:\s*\{/.exec(source)
      if (marker === null) throw new Error(`${label}: no \`security\` member is declared`)
      const after = source.slice(marker.index)
      const close = /\n\s*\}/.exec(after)
      return close === null ? after : after.slice(0, close.index)
    }
    const preloadMember = memberOf(preload, 'src/main/preload.ts')
    const paneMember = memberOf(panelsHalf, 'src/renderer/secure-panels.ts')
    for (const [label, member] of [['preload', preloadMember], ['pane', paneMember]] as const) {
      expect(/onChanged\(handler: \(\) => void\): \(\) => void/.test(member), `${label}: the security member declares the delivery, with the four members' \`tabs\`/\`view\`/\`module\` signature`).toBe(true)
    }
    expect(/ipcRenderer\.on\(IPC_SECURITY_CHANGED, listener\)/.test(preload), 'and the preload registers the CONSTANT on the channel the composition broadcasts on').toBe(true)
  })
})
